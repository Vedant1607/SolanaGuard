-- Backfill: keep existing paying users entitled (see header).
UPDATE "subscriptions"
   SET "paymentConfirmedAt" = "updatedAt"
 WHERE "plan" = 'PRO'
   AND "status" = 'active'
   AND "currentPeriodEnd" IS NOT NULL
   AND "paymentConfirmedAt" IS NULL;
