CREATE TYPE "BillingEventIdSource" AS ENUM ('PROVIDER_HEADER', 'BODY_SHA256');

-- CreateEnum
CREATE TYPE "BillingEventOutcome" AS ENUM ('PROCESSED', 'IGNORED', 'RECONCILIATION_REQUIRED');

-- CreateEnum
CREATE TYPE "RetirementReason" AS ENUM ('APP_CANCELLED', 'ALREADY_FINAL');

