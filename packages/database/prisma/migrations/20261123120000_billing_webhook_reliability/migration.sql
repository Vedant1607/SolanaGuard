-- A checkout attempt and its status are set together (both NULL on legacy rows).
ALTER TABLE "subscriptions" ADD CONSTRAINT "subscriptions_checkout_pair_check"
    CHECK (("checkoutAttemptId" IS NULL) = ("checkoutStatus" IS NULL));

-- "ca_" + 32 base64url characters (24 random bytes), as generated by billing-core.ts.
ALTER TABLE "subscriptions" ADD CONSTRAINT "subscriptions_checkoutAttemptId_format_check"
    CHECK ("checkoutAttemptId" IS NULL OR "checkoutAttemptId" ~ '^ca_[A-Za-z0-9_-]{32}$');

-- A cancellation intent is always bound to the Razorpay subscription it was made for.
ALTER TABLE "subscriptions" ADD CONSTRAINT "subscriptions_cancel_pair_check"
    CHECK (("cancelMode" IS NULL) = ("cancelSubscriptionId" IS NULL));

-- CreateTable
CREATE TABLE "retired_billing_subscriptions" (
    "razorpaySubscriptionId" TEXT NOT NULL,
    "userId" TEXT NOT NULL,
    "checkoutAttemptId" TEXT,
    "providerStatus" TEXT NOT NULL,
    "reason" "RetirementReason" NOT NULL,
    "retiredAt" TIMESTAMP(3) NOT NULL,

    CONSTRAINT "retired_billing_subscriptions_pkey" PRIMARY KEY ("razorpaySubscriptionId")
);

-- Only Razorpay subscription IDs and generated attempt IDs; retired only from a
-- final provider state, and an application cancel always ends "cancelled".
ALTER TABLE "retired_billing_subscriptions" ADD CONSTRAINT "retired_billing_subscriptions_values_check"
    CHECK ("razorpaySubscriptionId" ~ '^sub_[A-Za-z0-9]{1,40}$' AND
           ("checkoutAttemptId" IS NULL OR "checkoutAttemptId" ~ '^ca_[A-Za-z0-9_-]{32}$') AND
           "providerStatus" IN ('cancelled', 'completed', 'expired') AND
           ("reason" <> 'APP_CANCELLED' OR "providerStatus" = 'cancelled'));

-- CreateTable
CREATE TABLE "billing_webhook_events" (
    "id" TEXT NOT NULL,
    "idSource" "BillingEventIdSource" NOT NULL,
    "eventType" TEXT NOT NULL,
    "razorpaySubscriptionId" TEXT,
    "providerCreatedAt" TIMESTAMP(3),
    "receivedAt" TIMESTAMP(3) NOT NULL,
    "processedAt" TIMESTAMP(3),
    "outcome" "BillingEventOutcome",
    "reason" TEXT,
    "bodySha256" TEXT NOT NULL,
    "userId" TEXT,

    CONSTRAINT "billing_webhook_events_pkey" PRIMARY KEY ("id")
);

-- Only a lowercase hex SHA-256 fingerprint of the body is kept, never the body.
ALTER TABLE "billing_webhook_events" ADD CONSTRAINT "billing_webhook_events_bodySha256_check"
    CHECK ("bodySha256" ~ '^[0-9a-f]{64}$');

-- A fallback identity is exactly the namespaced body digest, so it can never
-- collide with, or pass for, a provider event ID.
ALTER TABLE "billing_webhook_events" ADD CONSTRAINT "billing_webhook_events_id_source_check"
    CHECK (char_length("id") BETWEEN 1 AND 128 AND
           (("idSource" = 'BODY_SHA256') = ("id" = 'body-sha256:' || "bodySha256")));

-- Short machine-readable codes only.
ALTER TABLE "billing_webhook_events" ADD CONSTRAINT "billing_webhook_events_codes_check"
    CHECK (char_length("eventType") BETWEEN 1 AND 64 AND
           ("reason" IS NULL OR "reason" ~ '^[a-z_]{1,64}$'));

-- Only a signed body that could not be parsed lacks a provider timestamp.
ALTER TABLE "billing_webhook_events" ADD CONSTRAINT "billing_webhook_events_unparsed_check"
    CHECK (("providerCreatedAt" IS NULL) = ("eventType" = 'unparsed'));

-- A committed row is always finished: outcome and processedAt are set together.
ALTER TABLE "billing_webhook_events" ADD CONSTRAINT "billing_webhook_events_outcome_check"
    CHECK (("outcome" IS NULL) = ("processedAt" IS NULL));

-- A user is associated with an event only together with its subscription, and
-- every reconciliation entry names its local owner and subscription.
ALTER TABLE "billing_webhook_events" ADD CONSTRAINT "billing_webhook_events_reconciliation_check"
    CHECK (("userId" IS NULL OR "razorpaySubscriptionId" IS NOT NULL) AND
           ("outcome" IS DISTINCT FROM 'RECONCILIATION_REQUIRED' OR "userId" IS NOT NULL));

