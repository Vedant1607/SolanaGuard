-- Razorpay billing reliability: checkout reservation, webhook idempotency and
-- event ordering.
--
-- Additive: five enum types, ten nullable columns on "subscriptions", two new
-- tables ("billing_webhook_events", "retired_billing_subscriptions"), their
-- indexes, foreign keys and CHECK constraints. No column is dropped, retyped or
-- made NOT NULL, and "subscriptions"."userId" stays UNIQUE (one row per user).
-- The enum, column, table and index statements were generated offline with
-- `prisma migrate diff` from schema.prisma; the CHECKs and backfill are hand-written.
--
-- Backfill (the only data change): rows written by the previous webhook as
-- PRO + active with a period end are marked payment-confirmed, so existing
-- paying users keep access under the new entitlement rule (which requires
-- confirmed payment). The previous webhook set PRO only on subscription.activated
-- or subscription.charged. No other row is touched.
--
-- Retired subscriptions: when an ended or stale unpaid Razorpay subscription is
-- detached (or a late charge arrives for an ended one), its ID, original owner
-- and checkout attempt are kept in "retired_billing_subscriptions".
-- Charge notifications that need an operator (ended subscription, or payload
-- notes disagreeing with the local owner) are recorded in "billing_webhook_events"
-- with outcome RECONCILIATION_REQUIRED and the LOCAL owner's "userId" (taken from
-- the exact local mapping, never from notes). Operator query:
--   SELECT e.id, e."eventType", e.reason, e."receivedAt", e."razorpaySubscriptionId", e."userId",
--          r."checkoutAttemptId" AS "retiredAttempt", r."retiredAt", r.reason AS retirement
--     FROM "billing_webhook_events" e
--     LEFT JOIN "retired_billing_subscriptions" r USING ("razorpaySubscriptionId")
--    WHERE e.outcome = 'RECONCILIATION_REQUIRED' ORDER BY e."receivedAt";
-- Both user foreign keys are ON DELETE RESTRICT: deleting a user with retired
-- subscriptions or user-attributed billing events fails until those have been
-- reconciled and archived.
--
-- Rollback (manual; Prisma has no down migrations). Deploy the previous
-- application code FIRST, export any RECONCILIATION_REQUIRED rows, then:
--   DROP TABLE IF EXISTS "billing_webhook_events";
--   DROP TABLE IF EXISTS "retired_billing_subscriptions";
--   ALTER TABLE "subscriptions"
--     DROP CONSTRAINT IF EXISTS "subscriptions_checkout_pair_check",
--     DROP CONSTRAINT IF EXISTS "subscriptions_checkoutAttemptId_format_check",
--     DROP CONSTRAINT IF EXISTS "subscriptions_cancel_pair_check",
--     DROP COLUMN IF EXISTS "cancelMode", DROP COLUMN IF EXISTS "cancelRequestedAt",
--     DROP COLUMN IF EXISTS "cancelSubscriptionId", DROP COLUMN IF EXISTS "checkoutAttemptId",
--     DROP COLUMN IF EXISTS "checkoutStartedAt", DROP COLUMN IF EXISTS "checkoutStatus",
--     DROP COLUMN IF EXISTS "endedAt", DROP COLUMN IF EXISTS "lastEventAt", DROP COLUMN IF EXISTS "lastEventType",
--     DROP COLUMN IF EXISTS "paymentConfirmedAt";
--   DROP TYPE IF EXISTS "CheckoutStatus"; DROP TYPE IF EXISTS "CancelMode";
--   DROP TYPE IF EXISTS "BillingEventIdSource"; DROP TYPE IF EXISTS "BillingEventOutcome";
--   DROP TYPE IF EXISTS "RetirementReason";
--   DELETE FROM "_prisma_migrations" WHERE migration_name = '20261123120000_billing_webhook_reliability';
-- Rolling back discards the webhook audit log, the retired-subscription
-- ownership records and any unresolved checkout reservations; reconcile those
-- in the Razorpay dashboard first.

